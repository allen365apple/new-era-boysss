/** 導讀只連到仍公開且屬於該分類的文章；標題從文章資料取得。 */
export function resolveTopicGuide(topic, posts) {
	const guide = TOPIC_GUIDES[topic.slug];
	return {
		...guide,
		startHere: guide.startHere.flatMap((entry) => {
			const post = posts.find((post) => post.id === entry.id && !post.data.draft && post.data.topics?.includes(topic.name));
			return post ? [{ ...entry, post }] : [];
		}),
	};
}
